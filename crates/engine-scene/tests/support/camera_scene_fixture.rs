//! Shared serialized scene text used by camera import and header tests.

pub(super) const LEGACY_HEADER: &str = concat!(
    "%UNITY 7.0\n",
    "%YAML 1.1\n",
    "%TAG !u! tag:unity3d.com,2011:\n"
);
pub(super) fn camera_project_scene() -> String {
    scene_with_header(LEGACY_HEADER)
}

pub(super) fn scene_with_header(header: &str) -> String {
    format!("{header}{CAMERA_PROJECT_DOCUMENTS}")
}

pub(super) fn replace_once(source: &str, expected: &str, replacement: &str) -> String {
    assert!(source.contains(expected), "fixture fragment must exist");
    source.replacen(expected, replacement, 1)
}

